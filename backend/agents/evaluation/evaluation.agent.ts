import { messageBus } from "../../services/message-bus.js";
import { AgentRequest, AgentResponse } from "../../models/orchestrator.types.js";
import { EvaluationReport } from "../../models/evaluation.types.js";
import { SecurityResult } from "../../models/security.types.js";
import { ReporterResult } from "../../models/reporter.types.js";
import { geminiService } from "../../services/gemini.service.js";

/**
 * Evaluation Agent (Mutagent Integration)
 * Evaluates the performance and accuracy of the pipeline before final output.
 */
export class EvaluationAgent {
  constructor() {
    this.startListening();
  }

  private startListening() {
    messageBus.subscribeToRequest("evaluation", async (req: AgentRequest) => {
      try {
        console.info(`[EvaluationAgent] Starting evaluation for session ${req.sessionId}`);
        const startTime = Date.now();
        
        const result = await this.run(req, startTime);
        
        const response: AgentResponse<EvaluationReport> = {
          sessionId: req.sessionId,
          agentId: "evaluation",
          status: "SUCCESS",
          data: result,
        };
        messageBus.publishResponse("evaluation", response);
      } catch (error: any) {
        console.error(`[EvaluationAgent] Failed evaluation for session ${req.sessionId}:`, error);
        messageBus.publishResponse("evaluation", {
          sessionId: req.sessionId,
          agentId: "evaluation",
          status: "FAILED",
          error: error.message,
        });
      }
    });
  }

  public async run(req: AgentRequest, startTime: number): Promise<EvaluationReport> {
    const security: SecurityResult = req.payload?.security || { passedChecks: 0, failedChecks: 0, findings: [] };
    const reporter: ReporterResult = req.payload?.reporter || {};
    const memory = req.payload?.memory || { duplicateCount: 0 };

    const totalChecks = security.passedChecks + security.failedChecks;
    const coverage = totalChecks > 0 ? 100 : 0;
    
    // Default metrics
    let falsePositiveRate = totalChecks > 0 ? (memory.duplicateCount / totalChecks) * 100 : 0;
    let accuracyScore = Math.max(100 - falsePositiveRate, 0);
    let verdict: "PASS" | "FAIL" | "NEEDS_HUMAN_REVIEW" = "PASS";
    let recommendations = [falsePositiveRate > 10 ? "Tune rule engine to reduce false positives." : "Pipeline operating normally."];

    try {
      const prompt = `You are an AI Evaluation Judge. Evaluate the accuracy of the following security findings generated by an automated scanner. Return a strictly formatted JSON object with the following keys:
      - verdict: "PASS" | "FAIL" | "NEEDS_HUMAN_REVIEW"
      - accuracyScore: number (0-100)
      - falsePositiveRate: number (0-100)
      - recommendations: string[] (1-2 sentences on how to improve the scanner based on these findings)`;
      
      const responseText = await geminiService.generateSummary({ findings: security.findings }, prompt);
      
      if (responseText && !responseText.includes('unavailable')) {
        // Strip out potential markdown block formatting
        const cleanJson = responseText.replace(/```json/g, '').replace(/```/g, '').trim();
        const aiEvaluation = JSON.parse(cleanJson);
        
        verdict = aiEvaluation.verdict || verdict;
        accuracyScore = aiEvaluation.accuracyScore ?? accuracyScore;
        falsePositiveRate = aiEvaluation.falsePositiveRate ?? falsePositiveRate;
        recommendations = aiEvaluation.recommendations || recommendations;
      }
    } catch (e) {
      console.error("[EvaluationAgent] Failed to use AI Judge, falling back to heuristics.", e);
    }

    if (accuracyScore < 80) verdict = "FAIL";
    else if (security.findings.length > 5 && reporter.overallRiskScore > 75) verdict = "NEEDS_HUMAN_REVIEW";

    return {
      verdict,
      accuracyScore,
      falsePositiveRate,
      falseNegativeRate: 0, // Hard to detect without a perfect oracle
      coverage,
      latencyMs: Date.now() - startTime,
      recommendations
    };
  }
}

export const evaluationAgent = new EvaluationAgent();
